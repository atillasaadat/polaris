/// @file Unit tests for the NRLMSIS 2.1 truth atmosphere (REQ-SIM-002, §5.2).
///
/// Two kinds of check.
///
/// **Golden.** `MsisGolden.MatchesNrlReferenceOutput` drives every case in
/// upstream's `msis2.1_test_in.txt` through the legacy interface and compares the
/// mass density against upstream's `msis2.1_test_ref_dp.txt`. Both files come from
/// the fetched tarball, never from our tree — so this validates the whole vendored
/// chain (download integrity, module build order, the -DDBLE precision flag)
/// against NRL's own numbers, without committing any MSIS-derived data. That
/// distinction matters: the MSIS license restricts data products generated by the
/// model, and a fixture we generated would carry that restriction into our repo
/// and outlive the model's eventual removal. Upstream's own file does not.
///
/// **Properties.** The wrapper tests pin what NRLMSIS buys over the exponential
/// atmosphere and cannot be faked by a static fit: the diurnal bulge, the
/// solar-activity dependence, and the ECI->ECEF reduction actually being applied.
/// They also pin the fail-safe behaviour, since a half-wired model must report no
/// atmosphere rather than a plausible guess.

