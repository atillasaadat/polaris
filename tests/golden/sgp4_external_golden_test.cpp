/// @file Three-way SGP4 cross-validation: Polaris vs FreeFlyer vs GMAT
/// (design doc §21.4, §23.1; REQ-ODP-003, REQ-CONV-002, REQ-VV-006).
///
/// `sgp4_verification_golden_test.cpp` is the acceptance test for the propagator
/// itself: it checks Polaris against the AIAA 2006-6753 reference vectors, in
/// TEME, to 1e-7 km. That proves Polaris reproduces **the reference**. It cannot
/// prove the chain a flight user actually calls — parse a TLE, propagate,
/// convert TEME to ECI — puts the satellite where other operational tools do,
/// because the reference vectors stop at TEME and never leave it.
///
/// This file closes that gap with two external tools that share nothing with
/// Polaris or with each other:
///
/// | tool             | SGP4 lineage                  | frame reported |
/// |------------------|-------------------------------|----------------|
/// | Polaris          | Vallado / AIAA 2006-6753      | TEME -> ECI    |
/// | FreeFlyer 7.10.1 | US Space Force AstroStds v9.5 | ICRF           |
/// | GMAT R2026a      | NAIF SPICE (`SPICESGP4`)      | ICRF           |
///
/// Three implementations, three codebases, three frame chains. Agreement across
/// them is evidence about the algorithm; agreement with only one could still be
/// a shared convention.
///
/// ## Why the bands are angular
///
/// The residual disagreement is a **constant angle**, not a growing error.
/// Across LEO, sun-synchronous LEO, a 12 h resonant Molniya, a 24 h synchronous
/// GEO and a non-resonant deep-space orbit — radii from 7000 km to beyond
/// 42 000 km — the linear disagreement spans a factor of ~7 while the angular
/// disagreement stays inside 0.06 arcsec. That is the signature of a frame
/// convention differing at the tens-of-milliarcseconds level, not of two
/// propagators diverging. A linear band would be five different numbers
/// describing one effect, so the bands here are stated in angle, and
/// `TheDisagreementIsAngularNotAPropagationDivergence` asserts that reading
/// rather than leaving it in this comment.
///
/// For scale: SGP4's own accuracy is about a kilometre at epoch. These
/// implementations agree three orders inside the theory's own error.
///
/// CI never runs FreeFlyer or GMAT; both fixtures are committed data,
/// regenerated by `tools/freeflyer/sgp4_fixture.py` and `tools/gmat/tle.py` and
/// drift-checked in the weekly `golden` lane.

