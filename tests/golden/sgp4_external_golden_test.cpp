TEST(Sgp4External, TheDisagreementIsAngularNotAPropagationDivergence) {
  // The claim the bands rest on, asserted rather than left in a comment.
  //
  // If Polaris differed from these tools in its *propagation*, the disagreement
  // would grow with arc length and would not scale with orbit radius. It does
  // the opposite: linear disagreement spans several metres across radii from
  // 7000 km to beyond 42 000 km, while the angular disagreement stays within a
  // factor of about two. That is one rotation seen at many radii.
  //
  // If this test ever fails, the bands above are describing the wrong thing and
  // must be re-derived — not widened.
  const json fixture = LoadFixture("freeflyer_sgp4.json");
  ASSERT_FALSE(fixture.is_discarded());

  double min_linear = 1.0e300;
  double max_linear = 0.0;
  double min_arcsec = 1.0e300;
  double max_arcsec = 0.0;
  for (const auto& [name, worst] : CompareAll(fixture)) {
    min_linear = std::min(min_linear, worst.linear_m);
    max_linear = std::max(max_linear, worst.linear_m);
    min_arcsec = std::min(min_arcsec, worst.arcsec);
    max_arcsec = std::max(max_arcsec, worst.arcsec);
  }
  ASSERT_GT(min_linear, 0.0);
  ASSERT_GT(min_arcsec, 0.0);

  const double linear_spread = max_linear / min_linear;
  const double angular_spread = max_arcsec / min_arcsec;
  EXPECT_GT(linear_spread, 3.0)
      << "the regimes no longer span a wide enough range of radii for this comparison to mean "
      << "anything (linear spread " << linear_spread << "x)";
  EXPECT_LT(angular_spread, linear_spread)
      << "the disagreement stopped looking like a frame rotation: linear spread " << linear_spread
      << "x, angular spread " << angular_spread << "x. If the angular spread now exceeds the "
      << "linear one, the difference is in the propagation rather than the frame.";
}

TEST(Sgp4External, TheTwoExternalToolsAgreeWithEachOther) {
  // Polaris is not the arbiter here. FreeFlyer and GMAT are independent of each
  // other as well as of Polaris, so differencing *them* bounds how much of the
  // residual above can be blamed on Polaris at all. If the two external tools
  // disagreed with each other by as much as each disagrees with Polaris, the
  // whole comparison would be measuring external-tool spread and would say
  // nothing about this repository's code.
  const json ff = LoadFixture("freeflyer_sgp4.json");
  const json gm = LoadFixture("gmat_sgp4.json");
  ASSERT_FALSE(ff.is_discarded());
  ASSERT_FALSE(gm.is_discarded());

  std::map<std::string, const json*> gmat_cases;
  for (const auto& c : gm.at("cases")) {
    gmat_cases[c.at("name").get<std::string>()] = &c;
  }

  int compared = 0;
  for (const auto& c : ff.at("cases")) {
    const std::string name = c.at("name").get<std::string>();
    const auto it = gmat_cases.find(name);
    if (it == gmat_cases.end()) {
      continue;  // deep_space_decaying — GMAT refuses it; see tools/gmat/tle.py.
    }
    const auto& gm_samples = it->second->at("samples");
    const auto& ff_samples = c.at("samples");
    ASSERT_EQ(ff_samples.size(), gm_samples.size()) << name;  // NOLINT — void test body
    for (std::size_t i = 0; i < ff_samples.size(); ++i) {
      EXPECT_DOUBLE_EQ(ff_samples[i].at("t_s").get<double>(), gm_samples[i].at("t_s").get<double>())
          << name << ": the two fixtures sample different instants";
      const auto a = ff_samples[i].at("position_km").get<std::vector<double>>();
      const auto b = gm_samples[i].at("position_km").get<std::vector<double>>();
      const Eigen::Vector3d va(a[0], a[1], a[2]);
      const Eigen::Vector3d vb(b[0], b[1], b[2]);
      const double arcsec = (va - vb).norm() / va.norm() * kArcsecPerRad;
      EXPECT_LT(arcsec, 0.20) << name << " at t=" << ff_samples[i].at("t_s").get<double>()
                              << " s: FreeFlyer and GMAT disagree by " << arcsec
                              << " arcsec, which is the scale of the Polaris comparison — "
                              << "the external tools must be tighter than the thing they bound.";
      ++compared;
    }
  }
  EXPECT_GT(compared, 0) << "no case names matched between the two fixtures";
}

TEST(Sgp4External, GmatIndependentlyConfirmsTheFrameBiasPolarisApplies) {
  // `lib/frames/teme_eci.cpp` composes eraBp00 because this repository's ECI is
  // GCRS while eraPmat76 precesses from FK5/J2000 — a ~23 mas bias, 0.8 m at
  // LEO. Left out, TLE-derived positions land in a *slightly different frame*
  // than the orbit filter's, with both spelled "ECI", and a pointing vector
  // formed by differencing them inherits the offset.
  //
  // The GMAT fixture reports every state in both ICRF (GCRS) and EarthMJ2000Eq
  // (FK5), which makes that decision falsifiable by a tool with no stake in it:
  // Polaris must land **closer to the ICRF column than to the FK5 one**. Drop
  // the eraBp00 term and this inequality reverses — it is the one assertion in
  // this file that fails if the bias is removed, and it fails in the right
  // direction rather than merely getting bigger.
  //
  // Stated as a total over all samples rather than per sample on purpose. The
  // bias is a rotation, so its effect on any *particular* vector depends on that
  // vector's direction relative to the rotation axis: the near-equatorial
  // deep-space case sees only 0.3 mas of it where LEO sees 20 mas. A per-sample
  // bound would therefore fail on geometry, not on correctness — which is
  // exactly the false alarm an earlier version of this test produced.
  const json fixture = LoadFixture("gmat_sgp4.json");
  ASSERT_FALSE(fixture.is_discarded());

  double total_to_icrf_m = 0.0;
  double total_to_fk5_m = 0.0;
  double worst_bias_arcsec = 0.0;
  int samples = 0;

  for (const auto& c : fixture.at("cases")) {
    gnc::TleElements tle;
    ASSERT_EQ(
        gnc::parseTle(c.at("tle_line1").get<std::string>(), c.at("tle_line2").get<std::string>(),
                      tle, gnc::TleChecksumPolicy::kIgnore),
        gnc::TleStatus::kOk);
    pt::Tai epoch;
    ASSERT_TRUE(tle.epochTai(pt::LeapSecondTable{}, epoch));
    gnc::Sgp4 propagator;
    ASSERT_EQ(propagator.initialise(tle, gnc::Sgp4OpsMode::kAfspc), gnc::Sgp4Status::kOk);

    for (const auto& s : c.at("samples")) {
      if (!s.contains("position_mj2000eq_km")) {
        continue;
      }
      const double t_s = s.at("t_s").get<double>();
      gnc::Sgp4::PositionKm r_teme;
      gnc::Sgp4::VelocityKmS v_teme;
      if (propagator.propagate(t_s / kSecondsPerMinute, r_teme, v_teme) != gnc::Sgp4Status::kOk) {
        continue;
      }
      pm::Vec3<pmf::ECI> r_eci;
      if (!pf::eciFromTeme(epoch + pt::Duration::fromSecondsF(t_s), r_teme, r_eci)) {
        continue;
      }
      const auto icrf = s.at("position_km").get<std::vector<double>>();
      const auto fk5 = s.at("position_mj2000eq_km").get<std::vector<double>>();
      const Eigen::Vector3d a(icrf[0], icrf[1], icrf[2]);
      const Eigen::Vector3d b(fk5[0], fk5[1], fk5[2]);
      total_to_icrf_m += (r_eci.eigen() - a).norm() * 1000.0;
      total_to_fk5_m += (r_eci.eigen() - b).norm() * 1000.0;
      worst_bias_arcsec = std::max(worst_bias_arcsec, (a - b).norm() / a.norm() * kArcsecPerRad);
      ++samples;
    }
  }

  ASSERT_GT(samples, 0) << "no sample carried position_mj2000eq_km — regenerate the fixture";
  std::printf(
      "\n  frame bias: Polaris->ICRF %.3f m total, Polaris->FK5 %.3f m total over %d "
      "samples; GMAT's own worst ICRF-vs-FK5 separation %.4f arcsec\n",
      total_to_icrf_m, total_to_fk5_m, samples, worst_bias_arcsec);

  // The bias must be a real, resolvable quantity in the fixture at all — else
  // this comparison would pass by both columns being identical.
  EXPECT_GT(worst_bias_arcsec, 0.005)
      << "GMAT's ICRF and EarthMJ2000Eq columns never differ meaningfully; the fixture is no "
      << "longer measuring the frame bias";
  EXPECT_LT(worst_bias_arcsec, 0.100) << "GMAT reports a frame bias of " << worst_bias_arcsec
                                      << " arcsec, far more than the ~23 mas the IAU bias explains";

  EXPECT_LT(total_to_icrf_m, total_to_fk5_m)
      << "Polaris's TEME->ECI output sits closer to GMAT's FK5 (EarthMJ2000Eq) column than to "
      << "its ICRF one — which is what omitting the eraBp00 frame-bias term looks like. "
      << "Polaris->ICRF " << total_to_icrf_m << " m vs Polaris->FK5 " << total_to_fk5_m << " m.";
}
